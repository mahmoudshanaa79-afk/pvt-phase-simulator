def system_discussion(
    system: str,
    rows: list[dict[str, str]],
    fit: dict[str, Any],
    document: dict[str, Any],
) -> str:
    if "optimum" not in fit:
        return ""
    optimum = fit["optimum"]
    loo = [item["train_kij"] for item in fit["leave_one_isotherm_out"]]
    low, high = min(loo), max(loo)
    inside = fit["bootstrap_low"] <= low and high <= fit["bootstrap_high"]
    stability = (
        "stays inside the bootstrap interval, so the optimum is stable across "
        "temperatures"
        if inside
        else "leaves the bootstrap interval, so the optimum drifts with the held-out "
        "temperature"
    )
    dew_zero = _row(rows, system, 0.0, "dew")
    dew_fit = _row(rows, system, optimum, "dew")
    change = _ambiguous(dew_fit) - _ambiguous(dew_zero)
    if change < 0:
        ambiguity = f"reduces the ambiguous dew states by {-change}"
    elif change > 0:
        ambiguity = f"adds {change} ambiguous dew states"
    else:
        ambiguity = "leaves the number of ambiguous dew states unchanged"
    fixed = set(fit["common_point_ids"])
    inside = [
        i["best_kij"] for i in fit["per_state_best_kij"] if i["point_id"] in fixed
    ]
    outside = [
        i["best_kij"]
        for i in fit["per_state_best_kij"]
        if i["point_id"] not in fixed and i["best_kij"] is not None
    ]
    unsolved = [
        i["point_id"][-3:] for i in fit["per_state_best_kij"] if i["best_kij"] is None
    ]
    spread = (
        f"- Each state's own best kij runs from {_kij(min(inside))} to "
        f"{_kij(max(inside))} inside the fixed set"
    )
    if len(outside) == 1:
        spread += (
            f", and is {_kij(outside[0])} for the one state outside it, whose "
            "convergence depends on kij"
        )
    elif outside:
        spread += (
            f", and from {_kij(min(outside))} to {_kij(max(outside))} for the "
            f"{len(outside)} states outside it, whose convergence depends on kij"
        )
    spread += "."
    if unsolved:
        spread += (
            f" No kij on the grid gives a converged bubble pressure for "
            f"{', '.join(unsolved)}."
        )
    return "\n".join(
        [
            "**Reading.**",
            "",
            (
                f"- Leaving out any one isotherm leaves the fitted kij at {_kij(low)}"
                f", inside the bootstrap interval."
                if low == high and stability.startswith("stays inside")
                else f"- Leaving one isotherm out moves the fitted kij between "
                f"{_kij(low)} and {_kij(high)}. That range {stability}."
            ),
            spread,
            f"- At the fitted kij the dew AARD over unique states is "
            f"{_aard(dew_fit)}, against {_aard(dew_zero)} at kij = 0. The fitted kij "
            f"{ambiguity} ({_ambiguous(dew_zero)} at kij = 0, "
            f"{_ambiguous(dew_fit)} at the fitted kij).",
            "",
        ]
    )


