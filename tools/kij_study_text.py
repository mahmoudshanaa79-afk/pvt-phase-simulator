def system_discussion(
    system: str,
    rows: list[dict[str, str]],
    fit: dict[str, Any],
    document: dict[str, Any],
) -> str:
    if "optimum" not in fit:
        return ""
    optimum = fit["optimum"]
    loo = [item["train_kij"] for item in fit["leave_one_isotherm_out"]]
    low, high = min(loo), max(loo)
    inside = fit["bootstrap_low"] <= low and high <= fit["bootstrap_high"]
    stability = (
        "stays inside the bootstrap interval, so the optimum is stable across "
        "temperatures"
        if inside
        else "leaves the bootstrap interval, so the optimum drifts with the held-out "
        "temperature"
    )
    dew_zero = _row(rows, system, 0.0, "dew")
    dew_fit = _row(rows, system, optimum, "dew")
    change = _ambiguous(dew_fit) - _ambiguous(dew_zero)
    if change < 0:
        ambiguity = f"reduces the ambiguous dew states by {-change}"
    elif change > 0:
        ambiguity = f"adds {change} ambiguous dew states"
    else:
        ambiguity = "leaves the number of ambiguous dew states unchanged"
    return "\n".join(
        [
            "**Reading.**",
            "",
            f"- Leaving one isotherm out moves the fitted kij between {_kij(low)} "
            f"and {_kij(high)}. That range {stability}.",
            f"- At the fitted kij the dew AARD over unique states is "
            f"{_aard(dew_fit)}, against {_aard(dew_zero)} at kij = 0. The fitted kij "
            f"{ambiguity} ({_ambiguous(dew_zero)} at kij = 0, "
            f"{_ambiguous(dew_fit)} at the fitted kij).",
            "",
        ]
    )


