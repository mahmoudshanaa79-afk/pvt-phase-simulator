"""Prose for docs/investigations/kij_study.md.

Statements that depend on results are computed from the study files, so the
wording cannot contradict the tables. Only the method, the literature and the
proposal options are fixed text.
"""

from __future__ import annotations

from typing import Any

BAND_PP = 0.1
LABELS = {
    "ch4_c2": "CH4+C2",
    "ch4_c3": "CH4+C3",
    "ch4_ic4": "CH4+iC4",
    "ch4_nc4": "CH4+nC4",
}


def _kij(value: float) -> str:
    return f"{value:+.4f}".replace("+0.0000", "0").replace("-0.0000", "0")


def _row(
    rows: list[dict[str, str]], system: str, kij: float, kind: str
) -> dict[str, str]:
    return next(
        r
        for r in rows
        if r["system_id"] == system and float(r["kij"]) == kij and r["kind"] == kind
    )


def _ambiguous(row: dict[str, str]) -> int:
    return int(row["hidden_root"]) + int(row["multiple_roots"])


def _aard(row: dict[str, str]) -> str:
    if row["aard_percent"] == "":
        return "n/a (n=0)"
    return f"{float(row['aard_percent']):.2f} % (n={row['aard_n']})"


def _production(rows: list[dict[str, str]]) -> list[str]:
    return list(
        dict.fromkeys(r["system_id"] for r in rows if r["provisional"] == "False")
    )


def title_and_summary(
    rows: list[dict[str, str]], fits: dict[str, Any], document: dict[str, Any]
) -> str:
    lines = [
        "# kij study (proposal P6)",
        "",
        "Generated by `tools/run_kij_study.py`; the text is rendered by",
        "`tools/kij_study_report.py` from `kij_study.csv` and `kij_study_fit.json`.",
        "Nothing here changes the engine or the kij = 0 validation record.",
        "",
        "**Question.** What does a non-zero binary interaction parameter kij do for",
        "Peng–Robinson on the May (2015) data, and should OpenPhase use one?",
        "",
        "## Summary",
        "",
    ]
    for system in _production(rows):
        fit = fits[system]
        if "optimum" not in fit:
            continue
        optimum = fit["optimum"]
        dew_zero = _row(rows, system, 0.0, "dew")
        dew_fit = _row(rows, system, optimum, "dew")
        composition = document["dew_composition"][system]
        lines += [
            f"- **{LABELS[system]}: fitted kij = {_kij(optimum)}** "
            f"(sensitivity band {_kij(fit['band_low'])} to {_kij(fit['band_high'])}). "
            f"Bubble AARD over a fixed set of {fit['common_n']} states falls from "
            f"{fit['aard_at_zero']:.2f} % to {fit['aard_at_optimum']:.2f} %.",
            f"  Out of sample, dew: {dew_zero['converged']} unique dew results at "
            f"kij = 0 and {dew_fit['converged']} at the fitted kij; ambiguous "
            f"(hidden or multiple roots) {_ambiguous(dew_zero)} and "
            f"{_ambiguous(dew_fit)}. Dew composition within 1 U: "
            f"{composition[0]['within_one_u']} of {composition[0]['assessed']} at "
            f"kij = 0, {composition[1]['within_one_u']} of "
            f"{composition[1]['assessed']} at the fitted kij.",
        ]
    lines += [
        "",
        "A kij fitted to these data is **calibration, not validation**: it is",
        "scored on the same measurements it was fitted to. Only the dew results and",
        "the leave-one-isotherm-out predictions are out of sample, and even those",
        "come from the same source and the same laboratory.",
        "",
    ]
    return "\n".join(lines)


METHOD = """## Method

- **Data.** May et al. (2015): 17 CH4+C2 and 23 CH4+C3 states (the production
  dataset), and, separately, the provisional butane points of the butane preview.
- **Solver.** Every state is solved with `calculate_saturation_pressure` and the
  production defaults (scanning solver, Newton refinement off), exactly as
  Module 17 does, plus a symmetric `binary_interactions` entry for the pair. At
  kij = 0 no interactions are passed, which is the engine's own default. The
  validation module itself fixes kij = 0, so it is not used to vary kij.
- **Outcomes** are named from the engine's own status and diagnostic codes:
  *converged* (a unique root), *not found*, *hidden root*
  (`inconclusive` with `HIDDEN_SATURATION_ROOT`), *multiple roots*
  (`inconclusive` with `MULTIPLE_SATURATION_ROOTS` seen directly by the scan),
  and any other status. Nothing is dropped. AARD is over converged states only,
  and n is always given.
- **Grid.** kij from -0.02 to 0.06 in steps of 0.005 for both directions; bubble
  pressure also on a 0.001 grid for the fit.
- **Fit.** kij minimises the bubble-pressure AARD over a *fixed* set of states:
  those that converge at every kij on the fine grid. A state that fails at some
  kij is left out of the objective, so the optimum cannot move because hard
  states drop in or out; such states are listed. The fine-grid minimum is
  refined with a bounded scalar search. Bubble pressure is used because it is
  well conditioned; dew pressure is not (`docs/DEW_INVESTIGATION.md`).
- **Sensitivity.** The band of kij whose fixed-set AARD is within 0.1
  percentage points of the minimum, and a 95 % bootstrap interval of the
  optimum (1000 resamples of the fixed set, fixed seed).
- **Leave one isotherm out.** States within 1 K form one isotherm. Each isotherm
  is held out in turn, kij is fitted on the rest of the fixed set, and the held-out
  states are scored at kij = 0 and at that kij. Most isotherms hold one or two
  states, so most held-out sets are tiny; the table gives every n.
- **Dew, out of sample.** Dew pressure is never used in the fit. Its status
  counts and unique-state AARD are reported at every kij.
- **Dew composition (P3 metric).** `analyze_dew_state` from
  `tools/run_dew_conditioning_study.py`, given the kij, compares PR's vapour
  composition at the measured pressure with the measured one, in units of the
  stated uncertainty U. It follows PR's bubble isotherm with Newton refinement,
  as the published P3 study does. At kij = 0 it reproduces the published P3
  output.
"""

