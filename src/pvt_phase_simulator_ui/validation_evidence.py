"""Further validation evidence shown on the Validation page.

Reads the committed investigation results under ``docs/investigations``. Nothing
here runs a calculation; each table is regenerated by its tool:

* ``dew_conditioning.csv``: ``tools/run_dew_conditioning_study.py`` (P3);
* ``validation_newton_comparison.csv``: ``tools/run_validation_newton_comparison.py``
  (P4);
* ``pure_saturation_comparison.csv``: ``tools/run_pure_saturation_study.py``
  (V2-01-E).
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Final

import pandas as pd  # type: ignore[import-untyped]
import streamlit as st

INVESTIGATIONS: Final = Path("docs") / "investigations"
DEW_CONDITIONING: Final = INVESTIGATIONS / "dew_conditioning.csv"
NEWTON_COMPARISON: Final = INVESTIGATIONS / "validation_newton_comparison.csv"
PURE_COMPARISON: Final = INVESTIGATIONS / "pure_saturation_comparison.csv"
PURE_PROVENANCE: Final = INVESTIGATIONS / "pure_saturation_reference_provenance.json"
SYSTEM_LABELS: Final = {"ch4_c2": "Methane + ethane", "ch4_c3": "Methane + propane"}
#: A composition uncertainty that alone allows more dew pressure than this is
#: treated as making the dew-pressure comparison uninformative.
ILL_POSED_SPREAD_PA: Final = 1.0e6


@st.cache_data(show_spinner=False)
def _read_csv(path: str) -> pd.DataFrame:
    return pd.read_csv(path)


def _missing(name: Path) -> None:
    st.info(
        f"`{name.as_posix()}` has not been generated in this deployment.",
        icon=":material/info:",
    )


def dew_conditioning_summary(frame: pd.DataFrame) -> pd.DataFrame:
    """Per-system counts behind the conditioning-aware dew metric (P3)."""

    rows = []
    for system, group in frame.groupby("system_id", sort=True):
        ratio = group["vapor_difference_over_uncertainty"].abs()
        rows.append(
            {
                "System": SYSTEM_LABELS.get(str(system), str(system)),
                "Dew states": len(group),
                "Within 1 U": int((ratio <= 1.0).sum()),
                "Within 2 U": int((ratio <= 2.0).sum()),
                "Ill-posed (> 1 MPa from U_y)": int(
                    (
                        group["pressure_spread_from_vapor_uncertainty_pa"]
                        > ILL_POSED_SPREAD_PA
                    ).sum()
                ),
                "Measured y above PR maximum": int(
                    (
                        group["experimental_vapor_ch4"]
                        > group["isotherm_vapor_ch4_maximum"]
                    ).sum()
                ),
            }
        )
    return pd.DataFrame(rows)


def newton_summary(frame: pd.DataFrame) -> pd.DataFrame:
    """Converged counts with and without Newton refinement, per direction (P4)."""

    rows = []
    for (system, direction), group in frame.groupby(
        ["system_id", "direction"], sort=True
    ):
        row = {
            "System": SYSTEM_LABELS.get(str(system), str(system)),
            "Direction": str(direction).capitalize(),
            "States": len(group),
            "Converged (default)": int((group["default_status"] == "converged").sum()),
            "Converged (Newton)": int((group["newton_status"] == "converged").sum()),
            "Accuracy results (default)": int(
                group["default_counts_as_accuracy"]
                .astype(str)
                .str.lower()
                .eq("true")
                .sum()
            ),
            "Accuracy results (Newton)": int(
                group["newton_counts_as_accuracy"]
                .astype(str)
                .str.lower()
                .eq("true")
                .sum()
            ),
        }
        rows.append(row)
    return pd.DataFrame(rows)


def pure_summary(frame: pd.DataFrame) -> pd.DataFrame:
    """Average absolute relative deviations per component (V2-01-E)."""

    rows = []
    for component, group in frame.groupby("component_id", sort=False):
        rows.append(
            {
                "Component": str(component).capitalize(),
                "States": len(group),
                "Vapour pressure AARD (%)": round(
                    100 * group["pressure_relative_error"].abs().mean(), 2
                ),
                "Liquid density AARD (%)": round(
                    100 * group["liquid_density_relative_error"].abs().mean(), 2
                ),
                "Vapour density AARD (%)": round(
                    100 * group["vapor_density_relative_error"].abs().mean(), 2
                ),
            }
        )
    return pd.DataFrame(rows)


def _dew_conditioning_tab(root: Path) -> None:
    st.markdown(
        "Near the maximum vapour composition of an isotherm, the dew pressure for "
        "a given vapour composition is extremely sensitive: a tiny change in *y* "
        "moves it by megapascals. This tab compares PR's vapour composition **at "
        "the measured pressure** with the measurement, in units of the stated "
        "expanded uncertainty *U*, and shows how much dew pressure the composition "
        "uncertainty alone allows."
    )
    path = root / DEW_CONDITIONING
    if not path.is_file():
        _missing(DEW_CONDITIONING)
        return
    frame = _read_csv(str(path))
    st.dataframe(dew_conditioning_summary(frame), hide_index=True, width="stretch")
    detail = pd.DataFrame(
        {
            "State": frame["source_point_id"],
            "T (K)": frame["temperature_k"].round(2),
            "P measured (MPa)": (frame["experimental_pressure_pa"] / 1e6).round(3),
            "y measured": frame["experimental_vapor_ch4"].round(4),
            "PR y maximum": frame["isotherm_vapor_ch4_maximum"].round(4),
            "dy / U": frame["vapor_difference_over_uncertainty"].round(2),
            "Dew-P spread from U_y (MPa)": (
                frame["pressure_spread_from_vapor_uncertainty_pa"] / 1e6
            ).round(2),
            "Production dew status": frame["production_dew_status"],
        }
    )
    with st.expander("All dew states"):
        st.dataframe(detail, hide_index=True, width="stretch")
    st.caption(
        "dy = y measured − y from PR at the measured pressure. Produced by "
        "tools/run_dew_conditioning_study.py from the unchanged engine."
    )


def _newton_tab(root: Path) -> None:
    st.markdown(
        "The production record runs the saturation solver with its defaults. "
        "This tab compares it with the same solver using the engine's Newton "
        "refinement. A converged dew pressure at a state where PR has more than "
        "one dew root is **one root of several**, not an accuracy result."
    )
    path = root / NEWTON_COMPARISON
    if not path.is_file():
        _missing(NEWTON_COMPARISON)
        return
    st.dataframe(newton_summary(_read_csv(str(path))), hide_index=True, width="stretch")
    st.caption(
        "Newton solves more near-critical bubble states, but those are also the "
        "least accurate ones, so the average error can rise. Produced by "
        "tools/run_validation_newton_comparison.py."
    )


def _pure_tab(root: Path) -> None:
    st.markdown(
        "The most basic check of an equation of state: PR against the published "
        "reference equations for each pure component."
    )
    path = root / PURE_COMPARISON
    if not path.is_file():
        _missing(PURE_COMPARISON)
        return
    st.dataframe(pure_summary(_read_csv(str(path))), hide_index=True, width="stretch")
    st.warning(
        "Saturated liquid densities from PR are off by up to about 12 % here (too "
        "dense far below Tc, not dense enough near it). No volume translation is "
        "implemented, so liquid densities are not quantitative.",
        icon=":material/warning:",
    )
    provenance_path = root / PURE_PROVENANCE
    if provenance_path.is_file():
        provenance = json.loads(provenance_path.read_text(encoding="utf-8"))
        sources = ", ".join(
            f"{name}: {fluid['equation_of_state']}"
            for name, fluid in provenance["fluids"].items()
        )
        st.caption(
            f"Reference equations of state ({sources}), evaluated with CoolProp "
            f"{provenance['coolprop_version']}. Produced by "
            "tools/run_pure_saturation_study.py."
        )


def render_further_evidence(root: Path) -> None:
    """Render the evidence tabs below the Module 17 figures."""

    st.subheader("Further evidence")
    conditioning, newton, pure = st.tabs(
        ["Dew conditioning", "Newton refinement", "Pure components"]
    )
    with conditioning:
        _dew_conditioning_tab(root)
    with newton:
        _newton_tab(root)
    with pure:
        _pure_tab(root)
